from typing import List
from pydantic import BaseModel, Field

class StepInfo(BaseModel):
    step: str = Field(..., description="Название шага")
    description: str = Field(..., description="Подробное описание действий")
    self_fix: List[str] = Field(..., description="Список ловушек и их решений")

class PlanIt(BaseModel):
    metrics: str
    metrics_reason: str
    arch: str
    arch_reason: str
    steps: List[StepInfo]

